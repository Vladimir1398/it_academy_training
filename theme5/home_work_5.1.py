# Импортируйте функцию randint из модуля random. Компьютер 
# загадывает случайное число от 1 до 50. У пользователя есть 
# ровно 5 попыток, чтобы его угадать. 
# ●     Используйте цикл while или for. 
# ●     На каждом шаге запрашивайте число. Если 
# пользователь угадал — прерывайте цикл и пишите 
# поздравление. 
# ●     Если введённое число меньше загаданного, пишите: 
# "Больше!". Если больше — пишите "Меньше!". 
# ●     Если попытки закончились, выведите правильный 
# ответ. 


from random import randint

secret = randint(1, 50)
guessed = False

for i in range(1, 6):
    guess = int(input("Введите число от 1 до 50: "))
    if guess == secret:
        print("Удачливый ты однако! Ответ верный")
        guessed = True
        break
    if guess < secret:
        print("Больше!!!")
    else:
        print("Меньше")

if not guessed:
    print("Ваши попытки закончились, повезёт в другой раз!")